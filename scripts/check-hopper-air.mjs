// Integración reproducible: conjunto de prueba a escala con toda su carga dinámica.
import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import {loadKernel} from '../src/kernel/occNode.js';
import {buildAssembly} from '../src/kernel/assemblyBuilder.js';
import {hopperCavity} from '../src/core/hopperFill.js';
import {ParticleSim,materialPresets} from '../src/particles/sim.js';
import {buildSdf} from '../src/particles/sdf.js';
const project=JSON.parse(readFileSync('examples/Tolva_prueba_escala.proj3d','utf8'));
const rep=await loadKernel(),built=buildAssembly(rep,project,{checkInterference:false});
const errors=built.parts.flatMap(p=>Object.values(p.results).filter(r=>r.status==='error'));assert.equal(errors.length,0);
const options={...project.simulation.initialFill,settleSeconds:.05};
const bodies=built.instances.map(i=>({mesh:i.mesh,sdf:buildSdf(i.mesh.vertices,i.mesh.triangles,{cell:.6,band:4}),movable:false}));
const plan=hopperCavity(built.instances.find(i=>i.id==='i1').mesh);
const sim=new ParticleSim(bodies,{...materialPresets.arena,radius:options.radius,cap:options.budget,maxCap:options.budget,rate:0,airModel:'calculado',airSolverCells:12000,initialFill:options,floorZ:-25});
sim.setScene({nozzles:project.nozzles.map(n=>({...n,tan:Math.tan((n.cone??0)/2*Math.PI/180)}))});sim.initializeFill(plan);
for(let i=0;i<2000&&sim.airPending();i++)sim.solveAirSlice(25);
assert.equal(sim.airPending(),false,'aire inicial finaliza');
assert.equal(sim.solverMode,true,'permanece en aire calculado');
const initial=sim.count;assert.ok(initial>5000,'carga completa, no sólo semillas de salida');
for(let i=0;i<4;i++)sim.step(1/60);
sim.setSettings({fillOpen:true,fillAir:true});
for(let i=0;i<15;i++)sim.step(1/60);
assert.equal(sim.hopper.airEnabled,true);assert.ok(sim.x.subarray(0,sim.count*3).every(Number.isFinite));
assert.equal(sim.count+sim.exited,initial);const state=sim.fillInfo();assert.ok(Math.abs(state.initialKg-state.activeKg-state.exitedKg)<1e-7);
console.log(JSON.stringify({phase:state.phase,capacityL:plan.capacity/1e6,initialKg:state.initialKg,count:sim.count,solver:sim.solverMode,airMessage:sim.airMessage,stepMs:sim.stepMs},null,2));
