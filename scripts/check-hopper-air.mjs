import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import {loadKernel} from '../src/kernel/occNode.js';
import {buildAssembly} from '../src/kernel/assemblyBuilder.js';
import {hopperCavity} from '../src/core/hopperFill.js';
import {ParticleSim,materialPresets} from '../src/particles/sim.js';
import {buildSdf} from '../src/particles/sdf.js';
const project=JSON.parse(readFileSync('examples/Tolva_llena.proj3d','utf8'));
const rep=await loadKernel(),built=buildAssembly(rep,project,{checkInterference:false});
const errors=built.parts.flatMap(p=>Object.values(p.results).filter(r=>r.status==='error'));assert.equal(errors.length,0);
const bodies=built.instances.map(i=>({mesh:i.mesh,sdf:buildSdf(i.mesh.vertices,i.mesh.triangles,{cell:2.1,band:7.5}),movable:false}));
const plan=hopperCavity(built.instances.find(i=>i.id==='i1').mesh);
const sim=new ParticleSim(bodies,{...materialPresets.arena,radius:3,cap:1000,rate:0,airModel:'calculado',airSolverCells:30000,initialFill:{...project.simulation.initialFill,settleSeconds:.05},floorZ:-25});
sim.setScene({nozzles:project.nozzles.map(n=>({...n,tan:Math.tan((n.cone??0)/2*Math.PI/180)}))});sim.initializeFill(plan);
for(let i=0;i<2000&&sim.airPending();i++)sim.solveAirSlice(25);
assert.equal(sim.airPending(),false,'aire inicial finaliza');
let deposited=0;const deposit=sim.hopper.deposit.bind(sim.hopper);sim.hopper.deposit=(...a)=>{deposited++;return deposit(...a);};
for(let i=0;i<30;i++)sim.step(1/60);
assert.ok(deposited>0);assert.ok(sim.x.subarray(0,sim.count*3).every(Number.isFinite));const s=sim.fillInfo();assert.ok(Math.abs(s.initialKg-s.reservoirKg-s.activeKg-s.exitedKg)<1e-7);
console.log(JSON.stringify({phase:s.phase,capacityL:plan.capacity/1e6,initialKg:s.initialKg,count:sim.count,solver:sim.solverMode,airMessage:sim.airMessage,depositCalls:deposited,stepMs:sim.stepMs},null,2));
