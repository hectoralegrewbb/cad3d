import assert from 'node:assert/strict';
import { loadKernel } from '../src/kernel/occNode.js';
import { createKernelService } from '../src/kernel/kernelService.js';
import { createPart } from '../src/core/partModel.js';
import { commands } from '../src/core/commands.js';
import { createProject, addInstance } from '../src/core/projectModel.js';
import { buildPart } from '../src/kernel/partBuilder.js';
import { extractMesh } from '../src/kernel/meshExtractor.js';
import { AirSolver } from '../src/particles/airSolver.js';
const rep = await loadKernel();
const kernel = createKernelService(rep);
let pipe = commands.addFeature(createPart('Tubo'), 'sketch');
pipe = commands.addEntity(pipe, 'sketch1', {t:'circle',x:0,y:0,d:20});
pipe = commands.addEntity(pipe, 'sketch1', {t:'circle',x:0,y:0,d:16});
pipe = commands.addFeature(pipe, 'extrude', {sketch:'sketch1', depth:20});
let project = createProject(pipe);
// Orden no contiguo de selección: z0 -> z40 -> z20.
for (const z of [0,40,20]) project = addInstance(project, 'p1', [0,0,z]);
const before = JSON.stringify(project);
const result = kernel.handle('weldAssembly', {project, ids:['i1','i2','i3']});
assert.equal(JSON.stringify(project), before, 'la unión no modifica el proyecto de entrada');
assert.ok(Math.abs(result.volume - Math.PI * (100-64) * 60) < .001);
const solid = rep.deserializeShape(result.brep);
const vertex = rep.makeVertex([0,0,20]);
const distance = new rep.DistanceTool();
assert.ok(distance.distanceBetween(solid,vertex)>7.99, 'el paso interior permanece abierto en la junta');
const weldedMesh = extractMesh(solid);
const sealedAir = new AirSolver({lo:[-15,-15,-5],hi:[15,15,65],cells:30000,bodies:[{mesh:weldedMesh,movable:false}]});
assert.equal(sealedAir.blockedLine(0,0,19,0,0,21),false,'el solver deja abierto el paso axial de la junta');
assert.equal(sealedAir.blockedLine(0,0,20,14,0,20),true,'el solver cierra la pared radial en la junta');
assert.equal(sealedAir.blockedLine(0,0,40,0,-14,40),true,'la segunda junta también conserva la pared');
distance.delete();vertex.delete();solid.delete();
let united=commands.addFeature(createPart('Unión'),'step',{brep:result.brep});
const built=buildPart(rep,united);assert.equal(built.results.step1.status,'ok');built.shape.delete();
const separated={...project,instances:project.instances.map(i=>i.id==='i3'?{...i,pos:[0,0,100]}:i)};
assert.throws(()=>kernel.handle('weldAssembly',{project:separated,ids:['i1','i3']}),/separados/);
assert.throws(()=>kernel.handle('weldAssembly',{project,ids:['i1','i1']}),/distintos/);
assert.throws(()=>kernel.handle('weldAssembly',{project,ids:['i1','missing']}),/B-Rep/);

// Membrana de un solo enlace de espesor: ni saltos largos ni diagonales la atraviesan.
const air=new AirSolver({lo:[0,0,0],hi:[10,10,10],cells:1000,bodies:[]});
const [nx,ny,nz]=air.dims;
air.au.fill(1);air.av.fill(1);air.aw.fill(1);
const x=air.origin[0]+air.hmm*4;
for(let k=0;k<nz;k++)for(let j=0;j<ny;j++)air.au[4+(nx+1)*(j+ny*k)]=0;
assert.equal(air.blockedLine(x-2.5*air.hmm,4.5*air.hmm,4.5*air.hmm,x+2.5*air.hmm,4.5*air.hmm,4.5*air.hmm),true);
assert.equal(air.blockedLine(x+2.5*air.hmm,4.5*air.hmm,4.5*air.hmm,x-2.5*air.hmm,4.5*air.hmm,4.5*air.hmm),true);
assert.equal(air.blockedLine(x-2.5*air.hmm,2.5*air.hmm,2.5*air.hmm,x+2.5*air.hmm,7.5*air.hmm,7.5*air.hmm),true);
assert.equal(air.blockedLine(1.5*air.hmm,2.5*air.hmm,2.5*air.hmm,2.5*air.hmm,2.5*air.hmm,2.5*air.hmm),false);
assert.equal(air.blockedLine(2.5*air.hmm,2.5*air.hmm,2.5*air.hmm,2.5*air.hmm,2.5*air.hmm,2.5*air.hmm),false);
assert.equal(air.blockedLine(2.5*air.hmm,2.5*air.hmm,2.5*air.hmm,-10,2.5*air.hmm,2.5*air.hmm),true);
console.log('weld y paredes de marcadores OK');
