import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import {particleConfig} from '../src/core/particleConfig.js';
import {hopperCavity} from '../src/core/hopperFill.js';
import {HopperLoad} from '../src/particles/hopperLoad.js';
import {ParticleSim,materialPresets} from '../src/particles/sim.js';
import {loadKernel} from '../src/kernel/occNode.js';
import {buildPart} from '../src/kernel/partBuilder.js';
import {extractMesh} from '../src/kernel/meshExtractor.js';
import {buildSdf} from '../src/particles/sdf.js';
import {parseProject} from '../src/core/projectModel.js';
import {ParticlePanel} from '../src/ui/particlePanel.js';
assert.throws(()=>particleConfig({initialFill:{percent:101}}),/fuera de rango/);
assert.throws(()=>particleConfig(null),/inválida/);
assert.throws(()=>particleConfig({initialFill:{budget:600001}}),/Presupuesto/);
const config=particleConfig({initialFill:{enabled:true,percent:50,target:'i1',radius:1,settleSeconds:.2,outletAxis:2,outletPosition:-4,outletSign:-1,outletU:0,outletV:0,outletRadius:20}});
assert.equal(particleConfig(JSON.parse(JSON.stringify(config))).initialFill.percent,50);
const events=[],panel=Object.create(ParticlePanel.prototype);
Object.assign(panel,{config:particleConfig({radiusMm:7.5}),persist(){events.push('save');},recorder:{reset(){events.push('reset');}},hooks:{onStop(){events.push('stop');},onStart(c){events.push(['start',c.radiusMm]);}}});panel.restart();assert.deepEqual(events,['save','stop','reset',['start',7.5]]);
const rep=await loadKernel();
const source=parseProject(readFileSync('examples/Proyecto_original.proj3d','utf8'));
const cone=source.parts[0].part.features[1],repaired=buildPart(rep,{...source.parts[0].part,features:[cone]});
assert.equal(repaired.results[cone.id].status,'ok');assert.ok(rep.measureVolume(repaired.shape)>550000&&rep.measureVolume(repaired.shape)<575000);repaired.shape.delete();
const shape=rep.makeBox([-12,-12,0],[12,12,30]).cut(rep.makeBox([-10,-10,-1],[10,10,31]));
const mesh=extractMesh(shape),plan=hopperCavity(mesh,{maxAxis:60}),sdf=buildSdf(mesh.vertices,mesh.triangles,{cell:.6,band:4});
const material=materialPresets.arena;
const make=percent=>{const sim=new ParticleSim([{sdf,mesh,movable:false}],{...material,radius:1,rate:0,cap:5000,maxCap:5000,initialFill:{...config.initialFill,percent},airCells:0,airModel:'rapido',floorZ:-15});sim.initializeFill(plan);return sim;};
let previous=0;
for(const percent of [0,25,50,100]){
 const sim=make(percent),initial=sim.count;assert.ok(initial>=previous);previous=initial;
 assert.equal(sim.fillInfo().reservoirKg,0,'ninguna carga oculta o visual');
 for(let i=0;i<18;i++)sim.step(1/60);
 assert.equal(sim.count,initial,'compuerta cerrada conserva toda la carga');assert.equal(sim.exited,0);assert.equal(sim.fillInfo().phase,'ready');
 sim.setSettings({fillOpen:true});assert.equal(sim.hopper.open,true);
 for(let i=0;i<55;i++)sim.step(1/60);
 assert.equal(sim.count+sim.exited,initial,'no se crean partículas al descargar');
 if(initial)assert.ok(sim.exited>initial*.8,'descarga por gravedad al abrir sin alimentación artificial');
 const info=sim.fillInfo();assert.ok(Math.abs(info.initialKg-info.activeKg-info.exitedKg)<1e-10);assert.ok(info.crossedKg<=info.initialKg+1e-10);
 assert.ok(sim.x.subarray(0,sim.count*3).every(Number.isFinite));
}
const small=new ParticleSim([{sdf,mesh}],{...material,radius:1,cap:100,maxCap:100,initialFill:{...config.initialFill,percent:100},airCells:0,airModel:'rapido'});assert.throws(()=>small.initializeFill(plan),/supera/,'no se acepta una carga parcial');
const load=new HopperLoad(plan,config.initialFill,material.density);const flags=new Uint8Array(2);
load.track(Float32Array.from([0,0,0,100,0,0]),Float32Array.from([0,0,-10,100,0,-10]),2,.1,.1,flags);assert.equal(load.crossed,1,'sólo cruces dentro de la sección');
load.track(Float32Array.from([0,0,0,100,0,0]),Float32Array.from([0,0,-10,100,0,-10]),2,.1,.2,flags);assert.equal(load.crossed,1,'no contar dos veces el mismo grano');
assert.throws(()=>new HopperLoad({...plan,rank:new Int32Array(0)},config.initialFill,material.density),/Grilla/);
const thin=rep.makeBox([-.1,-10,-1],[.1,10,20]),thinMesh=extractMesh(thin),thinSdf=buildSdf(thinMesh.vertices,thinMesh.triangles,{cell:4,band:4});
const fast=new ParticleSim([{mesh:thinMesh,sdf:thinSdf}],{...material,radius:1,cap:1000,maxCap:1000,rate:0,airCells:0,airModel:'rapido',initialFill:{...config.initialFill,percent:0,settleSeconds:0},floorZ:-100});
fast.initializeFill(plan);fast.hopper.open=true;fast.addFillParticle([-5,0,10]);fast.hopper.initialCount=1;fast.v.set([1200,0,0]);fast.step(1/60);
assert.ok(fast.x[0]<-.9,'una chapa de 0,2 mm detiene el grano rápido aunque el SDF sea de 4 mm');thin.delete();
assert.equal(source.parts[0].part.features[1].suppressed,undefined);shape.delete();
console.log('hopperFill: DEM completo 0/25/50/100, retención, descarga por gravedad, masa, sección finita, presupuesto y reinicio OK');
